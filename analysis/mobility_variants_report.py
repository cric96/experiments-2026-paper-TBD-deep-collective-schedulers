"""variants.md: one column per variant of the mobile experiment (``analysis.mobility_variants``)."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .mobility_pareto import METHODS
from .mobility_variants import HEURISTIC, LEARNERS, VARIANTS

FRONTIER_ROWS = {
    "fixed_ratio_bootstrap": "Error of 5 s / 0.5 s, bootstrap",
    "fixed_ratio_tracking": "Error of 5 s / 0.5 s, tracking",
    "fixed_ratio_switch": "Error of 5 s / 0.5 s, after the switch",
}
POLICY_ROWS = {
    "rounds_focus": "Rounds per episode (level 1)",
    "gain_episode": "Gain, whole episode (level 1)",
    "gain_bootstrap": "Gain, bootstrap (level 1)",
    "gain_tracking": "Gain, tracking (level 1)",
    "gain_switch": "Gain, after the switch (level 1)",
    "gain_post_static": "Gain after 40 s, static",
    "gain_post_focus": "Gain after 40 s, level 1",
    "gain_post_fastest": "Gain after 40 s, fastest level",
    "beta_range": "Rounds at beta 1 / beta 0.5 (level 1)",
    "level_response": "Rounds at fastest / static level",
    "reaction_static": "Rate after / before the switch, static",
    "reaction_focus": "Rate after / before the switch, level 1",
}


def _cell(row: pd.Series | None, quantity: str) -> str:
    if row is None or not np.isfinite(row["mean"]):
        return "—"
    if quantity.startswith("gain"):
        text = f"{row['mean']:+.0%}"
        return f"**{text}**" if row["low"] > 0 or row["high"] < 0 else text
    if quantity == "rounds_focus":
        return f"{row['mean']:,.0f}"
    return f"×{row['mean']:.2f}"


def _rows(summary: pd.DataFrame, algorithm: int, labels: dict[str, str], variants: list[str]) -> list[str]:
    indexed = summary[summary.algorithm == algorithm].set_index(["quantity", "variant"])
    lines = []
    for quantity, label in labels.items():
        cells = [_cell(indexed.loc[(quantity, key)] if (quantity, key) in indexed.index else None, quantity)
                 for key in variants]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def write_report(summary: pd.DataFrame, path: Path) -> None:
    variants = [variant for variant in VARIANTS if variant.key in set(summary.variant)]
    keys = [variant.key for variant in variants]
    header = ["| | " + " | ".join(variant.label for variant in variants) + " |", "|---" * (len(variants) + 1) + "|"]
    lines = ["# Incremental variants of the mobile experiment (generated by analysis.mobility_variants)", "",
             "Each variant adds one change to the previous one (the baseline is the original experiment):", "",
             *(f"- **{variant.label}**: {variant.change}" for variant in variants), "",
             "Levels: static (0), level 1 (D = 1 m²/s or 1 m/s) and the fastest (D = 4 m²/s or 2 m/s); beta = 0.95"
             " unless stated. Gains are paired by seed against the fixed-period frontier of the same variant, level"
             " and phase; bold = the 95% interval excludes zero. 4 seeds, 8 from the warm start on.", "",
             "## How much can the schedule matter? (fixed periods)", "", *header,
             *_rows(summary, -1, FRONTIER_ROWS, keys), ""]
    for algorithm in (*LEARNERS, HEURISTIC):
        lines += [f"## {METHODS[algorithm].label}", "", *header, *_rows(summary, algorithm, POLICY_ROWS, keys), ""]
    path.write_text("\n".join(lines))
